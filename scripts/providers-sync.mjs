#!/usr/bin/env node
// Provider catalogue generator (KoLo 2.0, M10).
//
//   pnpm providers:sync            fetch the public catalogue, refresh src/providers/upstream.json,
//                                  regenerate src/providers/registry.json
//   pnpm providers:sync --offline  regenerate registry.json from the committed upstream.json
//   pnpm providers:check           regenerate offline and fail when registry.json differs
//
// registry.json = curated entries (registry.curated.json, in order, winning on id) followed by
// generated entries from the public catalogue, sorted by id. Only providers with an https API
// base URL and an adapter Kurahi speaks are generated. Nothing here is product copy: display names
// are data, and the CLI's own sentences say "provider".
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CURATED_PATH = path.join(ROOT, "src/providers/registry.curated.json");
const UPSTREAM_PATH = path.join(ROOT, "src/providers/upstream.json");
const REGISTRY_PATH = path.join(ROOT, "src/providers/registry.json");
const UPSTREAM_URL = "https://models.dev/api.json";

const PROVIDER_ID = /^[a-z0-9][a-z0-9-]{0,63}$/;

/** Upstream adapter package -> KoLo API style. Packages not listed need a hand-written entry. */
const STYLE_BY_ADAPTER = {
  "@ai-sdk/openai": "openai-compatible",
  "@ai-sdk/openai-compatible": "openai-compatible",
  "@openrouter/ai-sdk-provider": "openai-compatible",
  "@ai-sdk/anthropic": "anthropic-messages",
  "@ai-sdk/google": "gemini",
};

const AUTH_BY_STYLE = {
  "openai-compatible": "bearer",
  "anthropic-messages": "x-api-key",
  gemini: "x-goog-api-key",
};

export function trimUpstream(raw, fetchedAt) {
  const providers = Object.values(raw)
    .filter((p) => p && typeof p === "object" && typeof p.id === "string")
    .map((p) => ({
      id: p.id,
      name: typeof p.name === "string" ? p.name : p.id,
      ...(typeof p.api === "string" ? { api: p.api } : {}),
      env: Array.isArray(p.env) ? p.env.filter((e) => typeof e === "string") : [],
      ...(typeof p.npm === "string" ? { npm: p.npm } : {}),
      ...(typeof p.doc === "string" ? { doc: p.doc } : {}),
    }))
    .sort((a, b) => a.id.localeCompare(b.id));
  return { source: UPSTREAM_URL, fetchedAt, providers };
}

export function generateRegistry(curated, upstream) {
  const entries = curated.providers.map((entry) => ({ ...entry }));
  const seen = new Set(entries.map((entry) => entry.id));
  const skipped = { curated: 0, noApi: 0, notHttps: 0, adapter: 0, badId: 0 };
  const generated = [];
  for (const p of upstream.providers) {
    if (seen.has(p.id)) {
      skipped.curated += 1;
      continue;
    }
    if (!PROVIDER_ID.test(p.id)) {
      skipped.badId += 1;
      continue;
    }
    if (!p.api) {
      skipped.noApi += 1;
      continue;
    }
    if (!p.api.startsWith("https://")) {
      skipped.notHttps += 1;
      continue;
    }
    const apiStyle = STYLE_BY_ADAPTER[p.npm ?? ""];
    if (!apiStyle) {
      skipped.adapter += 1;
      continue;
    }
    const baseUrl = p.api.replace(/\/+$/, "");
    generated.push({
      id: p.id,
      displayName: p.name,
      apiStyle,
      baseUrl,
      authHeader: AUTH_BY_STYLE[apiStyle],
      modelsEndpoint: "/models",
      regionNote: "Region not stated by the public catalogue; see the provider's documentation",
      ...(p.env[0] ? { envVar: p.env[0] } : {}),
      ...(p.doc ? { docUrl: p.doc } : {}),
      source: "catalogue",
    });
    seen.add(p.id);
  }
  generated.sort((a, b) => a.id.localeCompare(b.id));
  const registry = {
    $comment:
      "Generated by scripts/providers-sync.mjs: hand-maintained entries from registry.curated.json first, then entries derived from the public catalogue in upstream.json. Edit the curated file, never this one. Entries are configuration identifiers, never product copy.",
    version: 1,
    generated: {
      from: upstream.source,
      fetchedAt: upstream.fetchedAt,
      catalogueEntries: generated.length,
    },
    providers: [...entries, ...generated],
  };
  return { registry, skipped };
}

export function renderRegistry(registry) {
  return `${JSON.stringify(registry, null, 2)}\n`;
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

async function fetchUpstream() {
  const response = await fetch(UPSTREAM_URL, { headers: { accept: "application/json" } });
  if (!response.ok) {
    throw new Error(`${UPSTREAM_URL}: HTTP ${response.status}`);
  }
  return trimUpstream(await response.json(), new Date().toISOString().slice(0, 10));
}

async function main() {
  const args = new Set(process.argv.slice(2));
  const check = args.has("--check");
  const offline = check || args.has("--offline");
  const curated = readJson(CURATED_PATH);
  let upstream;
  if (offline) {
    upstream = readJson(UPSTREAM_PATH);
  } else {
    upstream = await fetchUpstream();
    fs.writeFileSync(UPSTREAM_PATH, `${JSON.stringify(upstream, null, 2)}\n`);
    console.log(
      `wrote ${path.relative(ROOT, UPSTREAM_PATH)} (${upstream.providers.length} upstream providers)`,
    );
  }
  const { registry, skipped } = generateRegistry(curated, upstream);
  const rendered = renderRegistry(registry);
  if (check) {
    const committed = fs.existsSync(REGISTRY_PATH) ? fs.readFileSync(REGISTRY_PATH, "utf8") : "";
    if (committed !== rendered) {
      console.error("providers: registry.json differs from the generated catalogue.");
      console.error(
        "Run `pnpm providers:sync --offline` (or `pnpm providers:sync`) and commit the result.",
      );
      process.exitCode = 1;
      return;
    }
    console.log(`providers: registry.json matches (${registry.providers.length} providers)`);
    return;
  }
  fs.writeFileSync(REGISTRY_PATH, rendered);
  console.log(
    `wrote ${path.relative(ROOT, REGISTRY_PATH)}: ${registry.providers.length} providers ` +
      `(${curated.providers.length} curated, ${registry.generated.catalogueEntries} from the catalogue; ` +
      `skipped: ${skipped.noApi} without an API URL, ${skipped.notHttps} not https, ${skipped.adapter} without a supported adapter, ${skipped.badId} with an invalid id)`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(`providers: ${err instanceof Error ? err.message : String(err)}`);
    process.exitCode = 1;
  });
}
