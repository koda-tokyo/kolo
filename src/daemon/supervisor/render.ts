// Pure renderers for the OS service definitions. No I/O here, so every platform's output
// can be snapshot-tested on any host.
import path from "node:path";
import type { ServiceIdentity } from "./identity.js";

export type ServiceLaunchSpec = {
  identity: ServiceIdentity;
  /** Absolute node (or bun) binary. */
  nodePath: string;
  /** Absolute CLI entry, e.g. <pkg>/dist/entry.js. */
  entryPath: string;
  /** Absolute path of the compiled runner (dist/daemon/supervisor/runner.js). */
  runnerPath: string;
  /** Extra non-secret environment (PATH, HOME). */
  environment: Record<string, string>;
  description?: string;
  version?: string;
};

export function gatewayArgs(spec: ServiceLaunchSpec): string[] {
  return [spec.nodePath, spec.entryPath, "gateway", "--port", String(spec.identity.port)];
}

function describe(spec: ServiceLaunchSpec): string {
  const version = spec.version ? `, v${spec.version}` : "";
  return spec.description ?? `KoLo Gateway (${spec.identity.id}${version})`;
}

// ---------------------------------------------------------------- systemd

/** systemd expands `%` specifiers and `$` variables in ExecStart/Environment; escape both. */
function systemdEscapeSpecifiers(value: string): string {
  return value.replaceAll("%", "%%");
}

export function systemdQuote(value: string): string {
  const escaped = systemdEscapeSpecifiers(value).replaceAll("$", () => "$$");
  if (escaped !== "" && !/[\s"'\\;]/.test(escaped)) {
    return escaped;
  }
  return `"${escaped.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

function systemdEnvLine(key: string, value: string): string {
  const assignment = systemdEscapeSpecifiers(`${key}=${value}`);
  if (!/[\s"'\\]/.test(assignment)) {
    return `Environment=${assignment}`;
  }
  return `Environment="${assignment.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

/**
 * Instance unit `kolo-gateway@<id>.service`. The gateway is the main process (no wrapper):
 * systemd loads the env file itself, restarts on any exit and owns the process state that
 * `kolo service status` reports.
 */
export function renderSystemdUnit(spec: ServiceLaunchSpec): string {
  const { identity } = spec;
  const env: Record<string, string> = {
    ...spec.environment,
    KOLO_SYSTEMD_UNIT: identity.systemdUnit,
  };
  const envLines = Object.keys(env)
    .toSorted()
    .map((key) => systemdEnvLine(key, env[key] ?? ""));
  return [
    "# Generated by `kolo service install`. Edit the env file, not this unit:",
    `#   ${identity.envFile}`,
    "[Unit]",
    `Description=${systemdEscapeSpecifiers(describe(spec))}`,
    "After=network-online.target",
    "Wants=network-online.target",
    // Never give up: the gateway exits on fatal errors and relies on the supervisor.
    "StartLimitIntervalSec=0",
    "",
    "[Service]",
    "Type=simple",
    `ExecStart=${gatewayArgs(spec).map(systemdQuote).join(" ")}`,
    `WorkingDirectory=${systemdEscapeSpecifiers(identity.home)}`,
    ...envLines,
    // Path settings take the raw value (no quoting); only specifiers need escaping.
    `EnvironmentFile=-${systemdEscapeSpecifiers(identity.envFile)}`,
    "Restart=always",
    "RestartSec=3",
    // Exit 3 = boot integrity gate refused (constitution file changed): do not restart-loop.
    "RestartPreventExitStatus=3",
    // mixed: SIGTERM to the gateway, SIGKILL to leftovers in the cgroup after the timeout.
    "KillMode=mixed",
    "KillSignal=SIGTERM",
    "TimeoutStopSec=15",
    "UMask=0077",
    "",
    "[Install]",
    "WantedBy=default.target",
    "",
  ].join("\n");
}

// ---------------------------------------------------------------- launchd

const plistEscape = (value: string): string =>
  value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");

/** Arguments for the runner: it loads the env file (launchd has no EnvironmentFile) and execs the gateway. */
export function runnerArgs(spec: ServiceLaunchSpec, opts: { restartLoop: boolean }): string[] {
  const { identity } = spec;
  const args = [spec.nodePath, spec.runnerPath, "--env-file", identity.envFile];
  args.push("--pid-file", path.join(identity.runDir, "gateway.pid"));
  if (opts.restartLoop) {
    args.push("--restart-loop", "--restart-sec", "3");
    args.push("--log-file", path.join(identity.logDir, "gateway.log"));
  }
  args.push("--", ...gatewayArgs(spec));
  return args;
}

export function renderLaunchdPlist(spec: ServiceLaunchSpec): string {
  const { identity } = spec;
  const env: Record<string, string> = {
    ...spec.environment,
    KOLO_LAUNCHD_LABEL: identity.launchdLabel,
  };
  const envItems = Object.keys(env)
    .toSorted()
    .map(
      (key) =>
        `\n      <key>${plistEscape(key)}</key>\n      <string>${plistEscape(env[key] ?? "")}</string>`,
    )
    .join("");
  const programArgs = runnerArgs(spec, { restartLoop: false })
    .map((arg) => `\n      <string>${plistEscape(arg)}</string>`)
    .join("");
  const out = path.join(identity.logDir, "gateway.out.log");
  const err = path.join(identity.logDir, "gateway.err.log");
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by \`kolo service install\`. Secrets belong in ${plistEscape(identity.envFile)} -->
<plist version="1.0">
  <dict>
    <key>Label</key>
    <string>${plistEscape(identity.launchdLabel)}</string>
    <key>Comment</key>
    <string>${plistEscape(describe(spec))}</string>
    <key>ProgramArguments</key>
    <array>${programArgs}
    </array>
    <key>WorkingDirectory</key>
    <string>${plistEscape(identity.home)}</string>
    <key>EnvironmentVariables</key>
    <dict>${envItems}
    </dict>
    <key>RunAtLoad</key>
    <true/>
    <key>KeepAlive</key>
    <true/>
    <key>ThrottleInterval</key>
    <integer>3</integer>
    <key>ExitTimeOut</key>
    <integer>15</integer>
    <key>Umask</key>
    <integer>63</integer>
    <key>ProcessType</key>
    <string>Background</string>
    <key>StandardOutPath</key>
    <string>${plistEscape(out)}</string>
    <key>StandardErrorPath</key>
    <string>${plistEscape(err)}</string>
  </dict>
</plist>
`;
}

// ---------------------------------------------------------------- Windows

/** cmd.exe quoting for one argument (we never pass these through a POSIX shell). */
export function cmdQuote(value: string): string {
  if (value !== "" && !/[\s"&|<>^%()!,;=]/.test(value)) {
    return value;
  }
  return `"${value.replaceAll('"', '""').replaceAll("%", "%%")}"`;
}

function cmdSetLine(key: string, value: string): string {
  return `set "${key}=${value.replaceAll("%", "%%").replaceAll('"', "")}"`;
}

/**
 * The Task Scheduler action. schtasks /TR is limited to 261 chars, so the action is this
 * wrapper; the restart loop, env file and log capture live in the Node runner.
 */
export function renderWindowsTaskScript(spec: ServiceLaunchSpec): string {
  const { identity } = spec;
  const env: Record<string, string> = {
    ...spec.environment,
    KOLO_WINDOWS_TASK_NAME: identity.windowsTaskName,
  };
  const lines = [
    "@echo off",
    `rem ${describe(spec)} - generated by "kolo service install". Secrets: ${identity.envFile}`,
    "setlocal",
    `cd /d ${cmdQuote(identity.home)}`,
    ...Object.keys(env)
      .toSorted()
      .map((key) => cmdSetLine(key, env[key] ?? "")),
    runnerArgs(spec, { restartLoop: true }).map(cmdQuote).join(" "),
    "",
  ];
  return lines.join("\r\n");
}

export function windowsTaskScriptPath(identity: ServiceIdentity): string {
  return path.join(identity.home, "service", "gateway.cmd");
}

/** `schtasks /Create` argv (passed to execFile, never a shell). */
export function buildSchtasksCreateArgs(params: {
  identity: ServiceIdentity;
  scriptPath: string;
  user?: string;
}): string[] {
  const args = [
    "/Create",
    "/F",
    "/TN",
    params.identity.windowsTaskName,
    "/SC",
    "ONLOGON",
    "/RL",
    "LIMITED",
    "/TR",
    `"${params.scriptPath}"`,
  ];
  if (params.user) {
    // /IT: run only while the user is logged on, so no password has to be stored.
    args.push("/RU", params.user, "/NP", "/IT");
  }
  return args;
}
